def _fake_dbt(monkeypatch, rcs):
    import shutil
    from pathlib import Path

    def fake(settings, batch_id, target_path):
        target_path.mkdir(parents=True, exist_ok=True)
        fixture = Path(__file__).parent / "fixtures" / "run_results.json"
        shutil.copy(fixture, target_path / "run_results.json")
        return rcs

    monkeypatch.setattr("ingest.dbt_runner.run_dbt", fake)


def test_dbt_build_succeeds_when_metrics_db_is_down(env, monkeypatch):
    monkeypatch.setenv("OBSERVABILITY_DB_URL", DOWN_DB)
